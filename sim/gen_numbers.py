"""Derive every number quoted in the paper from results.json -> numbers.tex."""
import json
import numpy as np
from params import F_CAM, T_PACE

R = json.load(open('results/results.json'))
VS = [50, 75, 100, 125, 150, 175, 200, 225, 250, 275, 300, 350, 400]
out = {}


def fmt_v(v_mm):
    return f'{v_mm / 1000:.3f}'.rstrip('0').rstrip('.') if v_mm % 50 else f'{v_mm / 1000:.2f}'


# ------------------------------------------------------------ kinematics ---
F = json.load(open('results/fine_windows.json'))
d = F['design']
fmt1 = lambda x: f'{x:.1f}'.rstrip('0').rstrip('.')
out['WinMin'], out['WinMax'] = fmt1(d['Lmin']), fmt1(d['Lmax'])
out['WinLo'], out['WinHi'] = fmt1(-d['lo']), fmt1(-d['hi'])
out['Lc_design'] = d['Lmin']
out['OmaxMin'], out['OmaxMax'] = fmt1(d['omax_near']), fmt1(d['omax_far'])
out['VrelMin'] = f"{d['vmin']:.2f}"
out['VrelMax'] = f"{d['vmax']:.2f}"
out['RcMin'] = str(int(round(d['rcmin'])))
out['MuLoMin'] = fmt1(min(F['mu0.3']['Lmin'], F['mu0.7']['Lmin'], d['Lmin']))
out['MuLoMax'] = fmt1(max(F['mu0.3']['Lmax'], F['mu0.7']['Lmax'], d['Lmax']))
out['MuHiMin'], out['MuHiMax'] = fmt1(F['mu1.3']['Lmin']), fmt1(F['mu1.3']['Lmax'])
out['WsMin'], out['WsMax'] = fmt1(F['w55.0']['Lmin']), fmt1(F['w55.0']['Lmax'])
out['WlMin'], out['WlMax'] = fmt1(F['w90.0']['Lmin']), fmt1(F['w90.0']['Lmax'])

# ---------------------------------------------------------- Monte Carlo ---
def vmax_ok(get, thr=0.99):
    best = None
    for v in VS:
        if get(v) >= thr:
            best = v
        else:
            break
    return best


mc = R['mc']
ok = lambda pm, ctl: (lambda v: min(mc[f'PLASTIC|{pm}|{v}'][ctl]['ok'],
                                    mc[f'ORGANIC|{pm}|{v}'][ctl]['ok']))
vb = vmax_ok(ok(0.0, 'prop'))
out['VmaxBoth'] = fmt_v(vb)
out['PropMin'] = f"{100 * min(ok(0.0, 'prop')(v) for v in VS if v <= vb):.1f}"
out['VmaxP'] = fmt_v(vmax_ok(lambda v: mc[f'PLASTIC|0.0|{v}']['prop']['ok']))
out['VmaxO'] = fmt_v(vmax_ok(lambda v: mc[f'ORGANIC|0.0|{v}']['prop']['ok']))
vpm = vmax_ok(ok(0.1, 'prop'))
out['VmaxPm'] = fmt_v(vpm)
out['BaseP'] = f"{100 * mc['PLASTIC|0.0|100']['base']['ok']:.0f}"
zero = [v for v in VS if mc[f'PLASTIC|0.0|{v}']['base']['ok'] == 0.0]
out['BaseZeroV'] = fmt_v(min(zero))
bb = R['base_best']
out['BaseBestP'] = f"{100 * bb['100']['ok']:.0f}"
out['BaseBestPTwo'] = f"{100 * bb['200']['ok']:.0f}"
out['BaseOrgMax'] = f"{100 * max(mc[f'ORGANIC|0.0|{v}']['base']['ok'] for v in VS):.0f}"
out['BaseContam'] = f"{100 * max(mc[f'ORGANIC|0.0|{v}']['base']['dist']['P'] for v in VS):.0f}"
out['EdgeMax'] = f"{max(R['reg'][k]['edge'] for k in R['reg'] if k.startswith('0.2|') and int(k.split('|')[1]) >= 50):.2f}"
out['Ntrials'] = str(R['mc_cfg']['N'])

# ------------------------------------------------- closed-form bounds (4) ---
def xstar(v, route):
    """|x*|(v), worst lateral position, interpolated over the speed grid."""
    vals = []
    for vv in VS:
        c = R['cw'][str(vv)]
        if route == 'P':
            vals.append(max(-(np.array(c['s_hi']) - 10.0)))
        else:
            vals.append(max(-(np.array(c['o_max']) - 5.0)))
    return float(np.interp(v, VS, vals))


def bound(route, T, Lv=300.0, g=200.0, m=1):
    tau_i = T - T_PACE
    v = 200.0
    for _ in range(200):
        v_new = (g + Lv - xstar(v, route)) / (m * T + tau_i + 1.0 / F_CAM)
        v = 0.5 * v + 0.5 * v_new
    return min(v, Lv / (m * T))


def fmt_b(v):
    return f'{v / 1000:.2f}'


cases = dict(Both=dict(T=1.0), Teight=dict(T=0.8), Ttwelve=dict(T=1.2),
             Lv=dict(T=1.0, Lv=400.0), Mtwo=dict(T=1.0, m=2))
for k, kw in cases.items():
    bp, bo = bound('P', **kw), bound('O', **kw)
    out['Vcf' + k] = fmt_b(min(bp, bo))
    if k == 'Both':
        out['VcfP'], out['VcfO'] = fmt_b(bp), fmt_b(bo)

# ------------------------------------------------------------ envelope ---
env = R['env']
for tag, name in (('T0.8', 'EnvTeight'), ('T1.2', 'EnvTtwelve'), ('m2', 'EnvMtwo'),
                  ('Lv400', 'EnvLv'), ('sig10', 'EnvSig')):
    g_ = lambda v, tag=tag: min(env[f'PLASTIC|{tag}|{v}'], env[f'ORGANIC|{tag}|{v}'])
    vm = vmax_ok(g_)
    out[name] = fmt_v(vm) if vm else '<0.05'

json.dump(out, open('results/numbers.json', 'w'), indent=1)
with open('../paper/numbers.tex', 'w') as f:
    f.write('% generated by sim/gen_numbers.py from sim/results/results.json\n')
    for k, v in out.items():
        if k in ('Lc_design',):
            continue
        f.write(f'\\newcommand{{\\{k}}}{{{v}}}\n')
for k, v in out.items():
    print(f'{k:14s} {v}')
